/**
 * 将经文索引中的中文书名替换为韩文书名
 * @param reference 原始经文索引，如 "以西结书 32:17~32"
 * @param lang 当前语言
 * @returns 韩文环境下返回替换后的字符串，如 "에스겔 32:17~32"
 */
export function localizeScriptureReference(reference: string | undefined | null, lang: 'zh' | 'ko'): string {
  if (!reference) return '';
  if (lang === 'zh') return reference;
  let result = reference;
  for (const [zh, ko] of Object.entries(ZH_TO_KO)) {
    if (result.includes(zh)) {
      result = result.replace(new RegExp(zh, 'g'), ko);
    }
  }
  return result;
}

/**
 * 将文本中的中文书名替换为韩文书名（用于标题等可能包含书名的文本）
 */
export function localizeBibleBookNames(text: string | undefined | null, lang: 'zh' | 'ko'): string {
  if (!text) return '';
  if (lang === 'zh') return text;
  let result = text;
  for (const [zh, ko] of Object.entries(ZH_TO_KO)) {
    if (result.includes(zh)) {
      result = result.replace(new RegExp(zh, 'g'), ko);
    }
  }
  return result;
}
