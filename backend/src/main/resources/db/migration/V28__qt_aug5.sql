今日经文摘要
忌邪的神向掠夺、藐视以色列地的外邦人宣告公义审判。以色列山要为归回的以色列百姓发枝结果，荒废之地将焕然一新。神必使人和牲畜如从前一样增多，土地也得着恢复，不再受外邦人的羞辱与毁谤。

向仇敌宣告审判｜36：1～7
耶和华向以色列山发预言，核心旨意是向以色列的仇敌宣告审判。耶路撒冷灭亡后，以东等周边外邦民族觊觎荒废的犹大地，竟夸口：「这永久的山冈都归我们为业了。」（2节）他们使以色列山荒凉，洗劫掠夺，使那地沦为多嘴多舌之人议论和毁谤的对象（3节）。耶和华宣告，祂必报应那些讥笑祂百姓和那地的人。对其余的外邦人和以东众人，耶和华说：「我真发愤恨如火」（5节），责备他们快乐满怀、心存恨恶，将祂的地归自己为业。正如以色列曾深陷受羞辱的境地，折磨以色列的国家也必蒙受羞辱。我们必须记得，神绝不看轻任何轻视、讥笑神百姓的罪。

神为何宣告要发愤恨如火，击打外邦民族和以东？看见肢体受苦时，我该如何说话，才能彰显神的怜悯？

以色列将要繁盛｜36：8～15
神应许以色列重得恢复与繁盛。以色列山必发枝结果（8节），迎接即将归回故土的以色列百姓。因耶和华转意眷顾并施行帮助，原先荒废的土地将恢复成生命之地。城邑将重新被建造，人和牲畜必将繁盛，以色列地将要改变，成为比从前更美好的蒙福之地（11节）。那地将彻底洗清污秽，不再背负「吞吃人」、「使国民丧子」这样的恶名（14节），也不会再被其他民族讥笑辱骂（15节）。神之所以更新这样荒废的土地，并使它恢复成丰盛繁荣之处，是为了使人知道祂就是耶和华。这也是提醒我们：即使生命此刻像荒废之地，也要信靠神，等候祂按其时日赐下恢复与果子。

